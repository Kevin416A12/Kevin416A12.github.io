#!/usr/bin/env python3
"""Generate Ana's voice clips with Kokoro-82M (Apache 2.0), voice af_heart.

Reads voice/VOICE_LINES.md, writes audio/voice/ana/<id>.mp3 for every line and
rebuilds audio/voice/ana/voice.js (the manifest the game reads).

Setup (once):  pip install kokoro soundfile     (needs espeak-ng and ffmpeg: brew install espeak-ng ffmpeg)
Run:           python3 scripts/make_voice.py
"""
import json, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "audio" / "voice" / "ana"

def read_lines():
    rows = []
    for line in (ROOT / "voice" / "VOICE_LINES.md").read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\| `([a-z0-9_]+)` \| (.+?) \| (\w+) \| \d+ \|$", line)
        if m:
            rows.append((m.group(1), m.group(2)))
    return rows

def main():
    try:
        import numpy as np, soundfile as sf
        from kokoro import KPipeline
    except ImportError:
        sys.exit("Missing packages. Run: pip install kokoro soundfile")
    OUT.mkdir(parents=True, exist_ok=True)
    pipe = KPipeline(lang_code="a")  # American English
    manifest = {}
    for vid, text in read_lines():
        audio = np.concatenate([chunk for _, _, chunk in pipe(text, voice="af_heart", speed=0.95)])
        wav = OUT / f"{vid}.wav"
        sf.write(wav, audio, 24000)
        mp3 = OUT / f"{vid}.mp3"
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(wav), "-codec:a", "libmp3lame", "-q:a", "4", str(mp3)], check=True)
        wav.unlink()
        manifest[vid] = mp3.name
        print("ok", vid)
    (OUT / "voice.js").write_text(
        "// Ana's recorded lines: id -> file. GENERATED by scripts/make_voice.py (Kokoro-82M, voice af_heart).\n"
        "window.SRO_VOICE = " + json.dumps(manifest, indent=1) + ";\n", encoding="utf-8")
    print(len(manifest), "clips written; manifest rebuilt")

if __name__ == "__main__":
    main()
