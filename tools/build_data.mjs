// Bundles the measured NASA-derived JSON files into js/data.js so the game
// runs from a static host (or a double-clicked file) with no fetch calls.
// Run: node tools/build_data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(readFileSync(join(root, 'data', f), 'utf8'));

const routes = read('route_options.json');
const illum = read('illumination_along_routes.json');
const lola = read('lola_measurements.json');
const lroc = read('lroc_wac_illumination_samples.json');
const signal = read('signal_along_routes.json');
const site = read('mission_site.json');
const sep = read('sep.json');
const flr = read('flr.json');

// Flare summary per UTC day: count and strongest class (no cherry-picking).
const rank = (c) => 'ABCMX'.indexOf(c[0]) * 100 + parseFloat(c.slice(1));
const flaresByDay = {};
for (const f of flr) {
  if (!f.classType) continue;
  const day = f.beginTime.slice(0, 10);
  const d = (flaresByDay[day] ||= { count: 0, strongest: f.classType });
  d.count += 1;
  if (rank(f.classType) > rank(d.strongest)) d.strongest = f.classType;
}
const classCounts = {};
for (const f of flr) if (f.classType) classCounts[f.classType[0]] = (classCounts[f.classType[0]] || 0) + 1;

// One entry per SEP record, as downloaded. Several instruments can report the
// same solar event, so the game draws ONE record per run and never adds them up.
const sepRecords = sep.map((s) => ({
  id: s.sepID,
  time: s.eventTime,
  day: s.eventTime.slice(0, 10),
  instrument: (s.instruments || []).map((i) => i.displayName).join('; '),
  link: s.link,
}));
const sepDays = {};
for (const s of sepRecords) sepDays[s.day] = (sepDays[s.day] || 0) + 1;

const bundle = {
  generated_from: ['route_options.json', 'illumination_along_routes.json', 'lola_measurements.json',
    'lroc_wac_illumination_samples.json', 'mission_site.json', 'sep.json', 'flr.json'],
  routes, illum, lola, lroc, site, signal,
  donki: {
    window: '2024-05-01 to 2024-05-15',
    flare_total: flr.length, flare_class_counts: classCounts, flaresByDay,
    sep_total: sepRecords.length, sepDays, sepRecords,
  },
};
const js = `// GENERATED by tools/build_data.mjs. Do not edit by hand.
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.SRO_DATA = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  return ${JSON.stringify(bundle, null, 1)};
});
`;
writeFileSync(join(root, 'js', 'data.js'), js);
console.log('js/data.js written:', js.length, 'bytes;', sepRecords.length, 'SEP records;', flr.length, 'flares');
